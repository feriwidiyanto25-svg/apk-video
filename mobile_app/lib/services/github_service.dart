import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'package:http/http.dart' as http;

class GitHubService {
  static const String apiBase = 'https://api.github.com';
  static const String uploadBase = 'https://uploads.github.com';

  static Map<String, String> _headers(String token) {
    return {
      'Authorization': 'Bearer $token',
      'Accept': 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
    };
  }

  /// Create a new GitHub Release for this Job with auto-retry & DNS warming
  static Future<int> createRelease({
    required String repo,
    required String token,
    required String tag,
    required String title,
    String? body,
    int maxRetries = 3,
  }) async {
    final url = Uri.parse('$apiBase/repos/$repo/releases');

    // Pre-warm DNS resolution
    try {
      await InternetAddress.lookup('api.github.com').timeout(const Duration(seconds: 4));
    } catch (_) {}

    int attempt = 0;
    while (true) {
      attempt++;
      try {
        final response = await http.post(
          url,
          headers: {
            ..._headers(token),
            'Content-Type': 'application/json',
          },
          body: jsonEncode({
            'tag_name': tag,
            'name': title,
            'body': (body != null && body.trim().isNotEmpty)
                ? body.trim()
                : 'Automated video rendering job generated by Shorts Creator App.',
            'draft': false,
            'prerelease': false,
          }),
        ).timeout(const Duration(seconds: 30));

        if (response.statusCode == 201 || response.statusCode == 200) {
          final data = jsonDecode(response.body);
          return data['id'] as int;
        } else {
          if (attempt >= maxRetries) {
            throw Exception('Gagal membuat Release GitHub (${response.statusCode}): ${response.body}');
          }
        }
      } catch (e) {
        if (attempt >= maxRetries) {
          if (e.toString().contains('Failed host lookup') ||
              e.toString().contains('SocketException') ||
              e.toString().contains('Connection closed')) {
            throw Exception(
              'Gagal terhubung ke api.github.com. Mohon periksa koneksi data/WiFi Anda.',
            );
          }
          rethrow;
        }
        await Future.delayed(Duration(milliseconds: 1500 * attempt));
      }
    }
  }

  /// Upload a binary asset (image, video, config JSON) to a Release with auto-retry and DNS warming
  static Future<void> uploadReleaseAsset({
    required String repo,
    required String token,
    required int releaseId,
    required String fileName,
    required Uint8List bytes,
    String contentType = 'application/octet-stream',
    int maxRetries = 4,
  }) async {
    final encodedName = Uri.encodeComponent(fileName);
    final url = Uri.parse('$uploadBase/repos/$repo/releases/$releaseId/assets?name=$encodedName');

    // Warm up DNS lookup for uploads.github.com to prevent cold lookup failures on mobile networks
    try {
      await InternetAddress.lookup('uploads.github.com').timeout(const Duration(seconds: 4));
    } catch (_) {}

    int attempt = 0;
    while (true) {
      attempt++;
      try {
        final response = await http.post(
          url,
          headers: {
            'Authorization': 'Bearer $token',
            'Content-Type': contentType,
            'X-GitHub-Api-Version': '2022-11-28',
          },
          body: bytes,
        ).timeout(const Duration(seconds: 90));

        if (response.statusCode == 201 || response.statusCode == 200) {
          return;
        } else if (response.statusCode == 422) {
          // 422 Unprocessable Entity usually means asset with this name is already uploaded
          return;
        } else {
          if (attempt >= maxRetries) {
            throw Exception('Gagal upload asset $fileName (${response.statusCode}): ${response.body}');
          }
        }
      } catch (e) {
        if (attempt >= maxRetries) {
          if (e.toString().contains('Failed host lookup') ||
              e.toString().contains('SocketException') ||
              e.toString().contains('Connection closed')) {
            throw Exception(
              'Gagal terhubung ke server upload GitHub (uploads.github.com). '
              'Koneksi internet atau DNS di HP sedang tidak stabil. '
              'Mohon periksa sinyal/WiFi Anda lalu coba kembali.',
            );
          }
          rethrow;
        }
        // Wait with progressive backoff before retrying
        await Future.delayed(Duration(milliseconds: 1500 * attempt));
      }
    }
  }

  /// Trigger GitHub Actions render_job.yml workflow via workflow_dispatch with auto-retry
  static Future<void> triggerRenderWorkflow({
    required String repo,
    required String token,
    required String jobId,
    int maxRetries = 3,
  }) async {
    final url = Uri.parse('$apiBase/repos/$repo/actions/workflows/render_job.yml/dispatches');

    int attempt = 0;
    while (true) {
      attempt++;
      try {
        final response = await http.post(
          url,
          headers: {
            ..._headers(token),
            'Content-Type': 'application/json',
          },
          body: jsonEncode({
            'ref': 'main',
            'inputs': {
              'job_id': jobId,
            },
          }),
        ).timeout(const Duration(seconds: 30));

        if (response.statusCode == 204 || response.statusCode == 200) {
          return;
        } else {
          if (attempt >= maxRetries) {
            throw Exception('Gagal memicu GitHub Action (${response.statusCode}): ${response.body}');
          }
        }
      } catch (e) {
        if (attempt >= maxRetries) {
          rethrow;
        }
        await Future.delayed(Duration(milliseconds: 1500 * attempt));
      }
    }
  }

  /// Check whether the video has finished rendering in the Release
  static Future<Map<String, dynamic>> checkJobStatus({
    required String repo,
    required String token,
    required String tag,
  }) async {
    final url = Uri.parse('$apiBase/repos/$repo/releases/tags/$tag');
    final response = await http.get(url, headers: _headers(token));

    if (response.statusCode != 200) {
      return {'status': 'rendering'};
    }

    final data = jsonDecode(response.body);
    final List assets = data['assets'] ?? [];

    for (var asset in assets) {
      final name = asset['name'].toString().toLowerCase();
      if (name == 'output_shorts.mp4') {
        return {
          'status': 'completed',
          'downloadUrl': asset['browser_download_url'],
          'assetUrl': asset['url'],
        };
      } else if (name == 'error.txt') {
        return {
          'status': 'failed',
          'error': 'Render gagal di GitHub Actions. Periksa log tindakan di GitHub.',
        };
      }
    }

    return {'status': 'rendering'};
  }

  /// Download the finished MP4 video file to local storage
  static Future<File> downloadFile({
    required String token,
    required String url,
    required String savePath,
  }) async {
    final response = await http.get(
      Uri.parse(url),
      headers: {
        'Authorization': 'Bearer $token',
        'Accept': 'application/octet-stream',
      },
    );

    if (response.statusCode == 200) {
      final file = File(savePath);
      await file.writeAsBytes(response.bodyBytes);
      return file;
    } else {
      throw Exception('Gagal mengunduh video hasil: ${response.statusCode}');
    }
  }

  /// Fetch all Releases from repository to sync jobs history across devices
  static Future<List<Map<String, dynamic>>> fetchJobReleases({
    required String repo,
    required String token,
  }) async {
    final url = Uri.parse('$apiBase/repos/$repo/releases?per_page=30');
    final response = await http.get(url, headers: _headers(token));

    if (response.statusCode != 200) {
      return [];
    }

    final List data = jsonDecode(response.body);
    final List<Map<String, dynamic>> results = [];

    for (var r in data) {
      final tag = r['tag_name']?.toString() ?? '';
      if (tag.startsWith('job-')) {
        String? videoUrl;
        final List assets = r['assets'] ?? [];
        for (var a in assets) {
          if (a['name']?.toString().toLowerCase() == 'output_shorts.mp4') {
            videoUrl = a['browser_download_url'];
            break;
          }
        }
        final releaseName = r['name']?.toString() ?? tag;
        final releaseBody = r['body']?.toString() ?? '';
        final cleanDesc = releaseBody.startsWith('Automated video rendering job') ? '' : releaseBody;

        results.add({
          'id': tag,
          'title': releaseName,
          'description': cleanDesc,
          'status': videoUrl != null ? 'completed' : 'rendering',
          'videoUrl': videoUrl,
          'createdAt': DateTime.tryParse(r['created_at'] ?? '') ?? DateTime.now(),
        });
      }
    }
    return results;
  }

  /// Delete a release and its git tag from GitHub
  static Future<void> deleteRelease({
    required String repo,
    required String token,
    required String tag,
  }) async {
    try {
      final getUrl = Uri.parse('$apiBase/repos/$repo/releases/tags/$tag');
      final getRes = await http.get(getUrl, headers: _headers(token));
      if (getRes.statusCode == 200) {
        final data = jsonDecode(getRes.body);
        final releaseId = data['id'];
        final delUrl = Uri.parse('$apiBase/repos/$repo/releases/$releaseId');
        await http.delete(delUrl, headers: _headers(token));
      }
      final tagUrl = Uri.parse('$apiBase/repos/$repo/git/refs/tags/$tag');
      await http.delete(tagUrl, headers: _headers(token));
    } catch (_) {}
  }
}
